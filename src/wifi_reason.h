#pragma once

/*
Код отказа радио -> причина, понятная человеку.

Ядро сообщает, почему станция отвалилась, числом (`last_reason`): 202, 201,
200. Числу не место на странице настройки: человек, набравший пароль с
ошибкой, должен прочитать «неверный пароль», а не «причина 202». Здесь же
решается, что делать дальше, - поэтому причина попадает и в JSON, и в лог.

Без Arduino: коды у ESP32 и ESP8266 одни и те же (IEEE 802.11 reason code
плюс свои с 200), и классификация проверяется на хосте (test/test_wifi_reason).
*/

#include <cstdint>

enum class WifiProblem : uint8_t {
    None,      // отказа не было
    Password,  // не приняли пароль: рукопожатие не состоялось
    NotFound,  // сети с таким именем нет в эфире - или она не по зубам
    Dropped,   // связь была и оборвалась не по нашей воле
    Other,     // код есть, но уверенно сказать по нему нечего
};

// Причина по коду ядра; 0 - отказа не было
WifiProblem wifi_problem(int reason);

// Короткое имя для JSON и логов: none, password, not_found, dropped, other
const char *wifi_problem_key(WifiProblem problem);

// Фраза для страницы настройки - то, что читает человек с телефоном
const char *wifi_problem_text(WifiProblem problem);
