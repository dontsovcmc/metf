#pragma once

/*
Пачка: что должно случиться на выводах платы.

Стенд заказывает форму сигнала, а не отдельные запросы, потому что всё, что
между фронтами, иначе отмеряет клиент через Wi-Fi. Заказанная пауза 0,3 с на
шаткой связи превращалась в две секунды, и тест испытуемого винил в этом его
прошивку.

Файл намеренно без Arduino.h и без обращений к регистрам: правила пачки -
сколько линий, сколько участков, какой уровень на участке, сколько всё это
длится - проверяются хостовыми тестами (test/test_wave). Таймеры и выводы
живут в bench_routes.
*/

#include <stdint.h>

namespace wave {

// Столько на плате слотов с таймерами - по одному на линию
constexpr uint8_t kMaxLines = 8;

// Участков на линию. Хватает и на дребезг (замкнуто-отпущено-замкнуто), и на
// серию из восьми импульсов
constexpr uint8_t kMaxEdges = 16;

// Пачка длиннее - это серия, и её ведёт стенд: ему в паузах всё равно надо
// вычитывать лог испытуемого, иначе кольцо переполняется
constexpr uint32_t kMaxBatchMs = 30000;

// Короче плата не отмерит: длительность заказывается в миллисекундах
constexpr uint32_t kMinEdgeMs = 1;

struct Line {
    uint8_t pin;
    uint8_t value;              // уровень первого участка, дальше чередуется
    uint32_t at_ms;             // смещение начала от общего старта пачки
    uint8_t count;              // участков
    uint32_t edges[kMaxEdges];  // длительности участков, мс
};

struct Batch {
    uint8_t count;
    Line lines[kMaxLines];
};

enum class Error : uint8_t {
    None,
    NoLines,
    TooManyLines,
    NoEdges,
    TooManyEdges,
    ShortEdge,
    TooLong,
    DuplicatePin,
};

/*
Уровень участка: нулевой участок идёт заказанным уровнем, дальше уровни
чередуются. Импульс - это «прижать и отпустить», и отпускание задавать
отдельным полем значило бы разрешить два подряд одинаковых участка.
*/
uint8_t level_at(const Line &line, uint8_t index);

/*
Проверить пачку и посчитать, сколько она длится целиком.

@param total_ms  длительность пачки: максимум по линиям от начала до последнего
                 отпускания. Заполняется только при Error::None
*/
Error check(const Batch &batch, uint32_t &total_ms);

/* Отказ словами - тем же текстом, что уходит клиенту в теле 400. */
const char *error_text(Error err);

} // namespace wave
